-- WhatsApp notifications through a retrying queue, phone numbers on profiles, 2FA for every role.
-- Run once in the Supabase SQL editor. Phone numbers themselves are never stored in this repository.

create extension if not exists pg_net;

-- ---------------------------------------------------------------- 2FA applies to anyone who enabled it

create function private.mfa_ok() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(auth.jwt() ->> 'aal', '') = 'aal2'
    or not exists (select 1 from auth.mfa_factors where user_id = auth.uid() and status = 'verified')
$$;

create or replace function private.my_child_id() returns int
language sql stable security definer set search_path = '' as $$
  select child_id from public.profiles
  where user_id = auth.uid() and role = 'child' and private.mfa_ok()
$$;

create or replace function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select private.mfa_ok()
    and exists (select 1 from public.profiles where user_id = auth.uid() and role = 'admin')
$$;

create or replace function private.is_guardian(cid int) returns boolean
language sql stable security definer set search_path = '' as $$
  select private.is_admin()
    or (private.mfa_ok() and exists (select 1 from public.parent_children where user_id = auth.uid() and child_id = cid))
$$;

grant execute on function private.mfa_ok() to authenticated;

create function public.admin_user_security()
returns table (user_id uuid, has_2fa boolean)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not private.is_admin() then raise exception 'Keine Berechtigung'; end if;
  return query
    select p.user_id, exists (select 1 from auth.mfa_factors f where f.user_id = p.user_id and f.status = 'verified')
    from public.profiles p;
end $$;

-- For a lost phone. The admin's own 2FA can only be removed in the Supabase dashboard.
create function public.admin_reset_2fa(target uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not private.is_admin() then raise exception 'Keine Berechtigung'; end if;
  if target = auth.uid() then raise exception 'Das eigene Konto geht hier nicht'; end if;
  delete from auth.mfa_factors where user_id = target;
end $$;

revoke all on function public.admin_user_security() from public, anon;
revoke all on function public.admin_reset_2fa(uuid) from public, anon;
grant execute on function public.admin_user_security() to authenticated;
grant execute on function public.admin_reset_2fa(uuid) to authenticated;

-- ---------------------------------------------------------------- phone numbers and queue

alter table public.profiles add column phone text check (phone ~ '^\+[0-9]{8,15}$');

create table public.notifications (
  id bigint generated by default as identity primary key,
  phone text not null,
  body text not null,
  status text not null default 'pending' check (status in ('pending', 'sending', 'sent', 'failed')),
  attempts int not null default 0,
  next_try timestamptz not null default now(),
  claimed_at timestamptz,
  sent_via text,
  last_error text,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);
create index notifications_open on public.notifications (next_try) where status in ('pending', 'sending');

alter table public.notifications enable row level security;
revoke all on public.notifications from anon;
create policy notifications_admin_read on public.notifications for select to authenticated
  using (private.is_admin());

-- ---------------------------------------------------------------- what gets sent

create function private.money(amount numeric) returns text
language sql immutable set search_path = '' as $$
  select to_char(amount, 'FM999999990.00') || ' CHF'
$$;

create function private.notify_new_request() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  child_name text;
begin
  select name into child_name from public.children where id = new.child_id;
  insert into public.notifications (phone, body)
  select p.phone,
         'KidsBank: ' || child_name || ' fragt ' || private.money(new.amount) ||
         case new.kind when 'withdrawal' then ' Auszahlung' else ' Einzahlung' end ||
         ' an: ' || new.description ||
         E'\nhttps://kidsbank.thetidyroutine.com/#/kind/' || new.child_id
  from public.profiles p
  where p.phone is not null
    and (p.role = 'admin'
         or exists (select 1 from public.parent_children pc where pc.user_id = p.user_id and pc.child_id = new.child_id));
  return null;
end $$;

create trigger notify_new_request after insert on public.requests
  for each row execute function private.notify_new_request();

create function private.notify_decision() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  child_name text;
  child_phone text;
begin
  if old.status <> 'pending' or new.status = 'pending' then return null; end if;
  select c.name, p.phone into child_name, child_phone
  from public.children c left join public.profiles p on p.child_id = c.id
  where c.id = new.child_id;

  if child_phone is not null then
    insert into public.notifications (phone, body) values (child_phone,
      'KidsBank: Deine Anfrage über ' || private.money(new.amount) || ' (' || new.description || ') wurde ' ||
      case new.status when 'approved' then 'genehmigt.' else 'abgelehnt.' end);
  end if;

  if new.status = 'approved' and new.kind = 'withdrawal' then
    insert into public.notifications (phone, body)
    select p.phone,
           'KidsBank: Jetzt per TWINT senden: ' || private.money(new.amount) || ' an ' || child_name ||
           coalesce(' (' || child_phone || ')', '') || E'\nGrund: ' || new.description
    from public.profiles p
    where p.user_id = new.decided_by and p.phone is not null;
  end if;
  return null;
end $$;

create trigger notify_decision after update of status on public.requests
  for each row execute function private.notify_decision();

