-- The sender function holds no data of its own: it asks the database what is due.
create function public.claim_notifications()
returns table (id bigint, phone text, body text)
language sql security definer set search_path = '' as $$
  update public.notifications n
     set status = 'sending', attempts = n.attempts + 1, claimed_at = now()
   where n.id in (
     select x.id from public.notifications x
     where x.attempts < 12
       and ((x.status = 'pending' and x.next_try <= now())
            or (x.status = 'sending' and x.claimed_at < now() - interval '5 minutes'))
     order by x.id
     limit 20
     for update skip locked)
  returning n.id, n.phone, n.body;
$$;

create function public.finish_notification(nid bigint, ok boolean, via text, error text) returns void
language sql security definer set search_path = '' as $$
  update public.notifications
     set status = case when ok then 'sent' when attempts >= 12 then 'failed' else 'pending' end,
         sent_via = case when ok then via else sent_via end,
         sent_at = case when ok then now() else sent_at end,
         last_error = case when ok then null else left(error, 300) end,
         next_try = now() + interval '5 minutes'
   where id = nid;
$$;

revoke all on function public.claim_notifications() from public, anon, authenticated;
revoke all on function public.finish_notification(bigint, boolean, text, text) from public, anon, authenticated;
grant execute on function public.claim_notifications() to service_role;
grant execute on function public.finish_notification(bigint, boolean, text, text) to service_role;

-- Retries while anything is due, closes rows that ran out of attempts, and removes old message text.
create function private.notifications_tick() returns void
language plpgsql security definer set search_path = '' as $$
begin
  update public.notifications set status = 'failed'
   where status in ('pending', 'sending') and attempts >= 12
     and (status = 'pending' or claimed_at < now() - interval '5 minutes');
  delete from public.notifications where created_at < now() - interval '90 days';
  if exists (
    select 1 from public.notifications
    where (status = 'pending' and next_try <= now())
       or (status = 'sending' and claimed_at < now() - interval '5 minutes')
  ) then
    perform private.wake_sender();
  end if;
end $$;

revoke all on function private.notifications_tick() from public, anon, authenticated;
revoke all on function private.wake_sender() from public, anon, authenticated;

select cron.schedule('kidsbank-notifications', '*/5 * * * *', 'select private.notifications_tick()');
