-- KidsBank schema. Run once in the Supabase SQL editor.
-- All permissions live here (row level security), so the public website holds no secrets.

create extension if not exists pgcrypto with schema extensions;
create extension if not exists pg_cron;

create schema if not exists private;
grant usage on schema private to authenticated;

-- ---------------------------------------------------------------- tables

create table public.children (
  id int generated by default as identity primary key,
  name text not null unique
);

create table public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  username text not null unique,
  role text not null check (role in ('admin', 'parent', 'child')),
  child_id int references public.children (id),
  check ((role = 'child') = (child_id is not null))
);

create table public.parent_children (
  user_id uuid not null references public.profiles (user_id) on delete cascade,
  child_id int not null references public.children (id) on delete cascade,
  primary key (user_id, child_id)
);

create table public.transactions (
  id bigint generated by default as identity primary key,
  child_id int not null references public.children (id) on delete restrict,
  date date not null default ((now() at time zone 'Europe/Zurich')::date),
  type text not null check (type in ('allowance', 'deposit', 'withdrawal', 'adjustment')),
  description text not null check (char_length(description) between 1 and 200),
  amount numeric(10, 2) not null check (amount <> 0),
  allowance_week date,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  unique (child_id, allowance_week)
);
create index transactions_child_date on public.transactions (child_id, date desc, id desc);

create table public.allowance_settings (
  child_id int primary key references public.children (id) on delete cascade,
  weekly_amount numeric(10, 2) not null check (weekly_amount > 0),
  start_date date not null,
  paid_through date not null
);

create table public.requests (
  id bigint generated by default as identity primary key,
  child_id int not null references public.children (id) on delete cascade,
  kind text not null check (kind in ('deposit', 'withdrawal')),
  amount numeric(10, 2) not null check (amount > 0),
  description text not null check (char_length(description) between 1 and 200),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  requested_by uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  decided_by uuid,
  decided_at timestamptz,
  transaction_id bigint references public.transactions (id) on delete set null
);
create index requests_child_status on public.requests (child_id, status);

create table public.goals (
  id bigint generated by default as identity primary key,
  child_id int not null references public.children (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  target_amount numeric(10, 2) not null check (target_amount > 0),
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- permission helpers

create function private.my_child_id() returns int
language sql stable security definer set search_path = '' as $$
  select child_id from public.profiles where user_id = auth.uid() and role = 'child'
$$;

-- An admin with 2FA set up only counts as admin after entering the code in this session.
create function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where user_id = auth.uid() and role = 'admin')
    and (
      coalesce(auth.jwt() ->> 'aal', '') = 'aal2'
      or not exists (select 1 from auth.mfa_factors where user_id = auth.uid() and status = 'verified')
    )
$$;

create function private.is_guardian(cid int) returns boolean
language sql stable security definer set search_path = '' as $$
  select private.is_admin()
    or exists (select 1 from public.parent_children where user_id = auth.uid() and child_id = cid)
$$;

create function private.can_read_child(cid int) returns boolean
language sql stable security definer set search_path = '' as $$
  select private.my_child_id() = cid or private.is_guardian(cid)
$$;

grant execute on all functions in schema private to authenticated;

-- ---------------------------------------------------------------- row level security

alter table public.children enable row level security;
alter table public.profiles enable row level security;
alter table public.parent_children enable row level security;
alter table public.transactions enable row level security;
alter table public.allowance_settings enable row level security;
alter table public.requests enable row level security;
alter table public.goals enable row level security;

revoke all on all tables in schema public from anon;
revoke all on all sequences in schema public from anon;

create policy children_read on public.children for select to authenticated
  using (private.can_read_child(id));
create policy children_admin on public.children for all to authenticated
  using (private.is_admin()) with check (private.is_admin());

create policy profiles_read on public.profiles for select to authenticated
  using (user_id = auth.uid() or private.is_admin());
create policy profiles_admin on public.profiles for all to authenticated
  using (private.is_admin()) with check (private.is_admin());

create policy parent_children_read on public.parent_children for select to authenticated
  using (user_id = auth.uid() or private.is_admin());
create policy parent_children_admin on public.parent_children for all to authenticated
  using (private.is_admin()) with check (private.is_admin());

create policy transactions_read on public.transactions for select to authenticated
  using (private.can_read_child(child_id));
create policy transactions_admin on public.transactions for all to authenticated
  using (private.is_admin()) with check (private.is_admin());

create policy allowance_read on public.allowance_settings for select to authenticated
  using (private.can_read_child(child_id));
create policy allowance_admin on public.allowance_settings for all to authenticated
  using (private.is_admin()) with check (private.is_admin());

create policy requests_read on public.requests for select to authenticated
  using (private.can_read_child(child_id));
create policy requests_child_create on public.requests for insert to authenticated
  with check (
    child_id = private.my_child_id()
    and requested_by = auth.uid()
    and status = 'pending' and decided_by is null and decided_at is null and transaction_id is null
  );
create policy requests_child_withdraw on public.requests for delete to authenticated
  using (child_id = private.my_child_id() and status = 'pending');

create policy goals_read on public.goals for select to authenticated
  using (private.can_read_child(child_id));
create policy goals_write_own on public.goals for all to authenticated
  using (child_id = private.my_child_id() or private.is_admin())
  with check (child_id = private.my_child_id() or private.is_admin());

-- ---------------------------------------------------------------- balances

create view public.child_balances with (security_invoker = true) as
  select c.id as child_id, c.name,
         coalesce(sum(t.amount), 0)::numeric(10, 2) as balance
  from public.children c
  left join public.transactions t on t.child_id = c.id
  group by c.id, c.name;

revoke all on public.child_balances from anon;

-- ---------------------------------------------------------------- actions

create function public.decide_request(request_id bigint, approve boolean) returns void
language plpgsql security definer set search_path = '' as $$
declare
  r public.requests;
  tx_id bigint;
begin
  select * into r from public.requests where id = request_id for update;
  if r.id is null then raise exception 'Anfrage nicht gefunden'; end if;
  if not private.is_guardian(r.child_id) then raise exception 'Keine Berechtigung'; end if;
  if r.status <> 'pending' then raise exception 'Anfrage wurde bereits entschieden'; end if;

  if approve then
    insert into public.transactions (child_id, type, description, amount, created_by)
    values (r.child_id, r.kind, r.description,
            case r.kind when 'withdrawal' then -r.amount else r.amount end, auth.uid())
    returning id into tx_id;
  end if;

  update public.requests
     set status = case when approve then 'approved' else 'rejected' end,
         decided_by = auth.uid(), decided_at = now(), transaction_id = tx_id
   where id = request_id;
end $$;

-- Lets the admin reset a family member's password from inside the app.
create function public.admin_set_password(target uuid, new_password text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not private.is_admin() then raise exception 'Keine Berechtigung'; end if;
  if char_length(new_password) < 8 then raise exception 'Mindestens 8 Zeichen'; end if;
  update auth.users
     set encrypted_password = extensions.crypt(new_password, extensions.gen_salt('bf')),
         updated_at = now()
   where id = target;
  if not found then raise exception 'Benutzer nicht gefunden'; end if;
end $$;

revoke all on function public.decide_request(bigint, boolean) from public, anon;
revoke all on function public.admin_set_password(uuid, text) from public, anon;
grant execute on function public.decide_request(bigint, boolean) to authenticated;
grant execute on function public.admin_set_password(uuid, text) to authenticated;

-- ---------------------------------------------------------------- weekly allowance

-- A new allowance starts now: past Sundays are not paid out retroactively.
create function private.allowance_defaults() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.paid_through is null then
    new.paid_through := (now() at time zone 'Europe/Zurich')::date - 1;
  end if;
  return new;
end $$;

create trigger allowance_defaults before insert on public.allowance_settings
  for each row execute function private.allowance_defaults();

-- Pays every Sunday not yet paid, so a missed run catches up. Safe to run any number of times.
create function private.pay_allowances() returns int
language plpgsql security definer set search_path = '' as $$
declare
  s record;
  today date := (now() at time zone 'Europe/Zurich')::date;
  from_day date;
  sunday date;
  paid int := 0;
  added int;
begin
  for s in select * from public.allowance_settings for update loop
    from_day := greatest(s.paid_through, s.start_date - 1);
    sunday := from_day + (7 - extract(dow from from_day)::int);
    while sunday <= today loop
      insert into public.transactions (child_id, date, type, description, amount, allowance_week, created_by)
      values (s.child_id, sunday, 'allowance',
              'Wöchentliches Taschengeld - ' || to_char(sunday, 'DD.MM.YYYY'),
              s.weekly_amount, sunday, null)
      on conflict (child_id, allowance_week) do nothing;
      get diagnostics added = row_count;
      paid := paid + added;
      update public.allowance_settings set paid_through = sunday where child_id = s.child_id;
      sunday := sunday + 7;
    end loop;
  end loop;
  return paid;
end $$;

revoke all on function private.pay_allowances() from public, anon, authenticated;

select cron.schedule('kidsbank-allowance', '7 * * * *', 'select private.pay_allowances()');
